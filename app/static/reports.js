/* Reports page: render the generated markdown reports from reports/ (plus the model card next
   to the artifact). Figures inside them are fetched through /api/report/<basename>. */
(async function () {
  const { $, $$, esc, api, load } = VFA;
  const s = await load();
  VFA.decorate(s);

  const box = $('#reportLinks'), view = $('#reportView'), meta = $('#reportMeta');
  const names = ((s.health || {}).reports_available || []);
  const all = names.concat(names.indexOf('MODEL_CARD.md') >= 0 ? [] : ['MODEL_CARD.md']);

  if (!all.length) {
    box.innerHTML = '<span class="hint">no reports in <code>reports/</code> yet — <code>python train.py</code> writes them</span>';
    view.innerHTML = '<p class="prose">The training run produces the dataset inspection, the model comparison, the '
      + 'training report and the model card. Until then this page has nothing to render, and it will not invent a summary.</p>';
    return;
  }

  box.innerHTML = all.map((n) => `<button type="button" class="btn ghost sm" data-r="${esc(n)}">${esc(n.replace(/\.md$/, ''))}</button>`).join('');

  async function show(name) {
    const btn = $$('button', box).find((b) => b.dataset.r === name);
    $$('button', box).forEach((b) => b.classList.toggle('active', b === btn));
    if (meta) meta.textContent = `reading ${name}…`;
    try {
      const j = await api('/api/report/' + encodeURIComponent(name));
      view.innerHTML = j.markdown ? VFA.mdLite(j.markdown) : `<pre>${esc(JSON.stringify(j, null, 1))}</pre>`;
      if (meta) meta.textContent = `${esc(j.name || name)}${j.written_at ? ` · written ${j.written_at}` : ''}`
        + ' · generated by the pipeline, rendered here without editing';
    } catch (err) {
      view.innerHTML = `<p class="prose">Could not read ${esc(name)}: ${esc(err.message)}</p>`;
      if (meta) meta.textContent = 'unavailable';
    }
  }

  box.addEventListener('click', (e) => {
    const b = e.target.closest('button[data-r]');
    if (b) show(b.dataset.r);
  });

  const first = all.indexOf('model_comparison.md') >= 0 ? 'model_comparison.md' : all[0];
  show(first);
})();
